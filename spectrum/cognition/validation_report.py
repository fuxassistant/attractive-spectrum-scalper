"""Readable report of the frozen March-April validation (reads its summary only)."""
from datetime import datetime, timezone
from pathlib import Path
import json

REPORT = Path('reports/validation_v1')
WORD = dict(PASS='ПРОЙДЕНА', FAIL='НЕ ПРОЙДЕНА', NO_TRADE='НЕТ СДЕЛОК')


def ci(x):
    return f"{x['mean']:+.3f} [{x['lower']:+.3f}; {x['upper']:+.3f}]"


def day(ns):
    return str(datetime.fromtimestamp(int(ns) / 1e9, timezone.utc).date())


def markdown(s, pre):
    v = s['verdicts']; sc = s['schemas']
    L = ['# Проверка замороженной процедуры на март–апрель 2026', '',
         f"Блок V: {s['days_V']} торговых дней, {s['origins_V']} точек входа. Процедура и критерии зафиксированы до генерации данных "
         '(`PREREGISTRATION_RU.md`, коммит заморозки и одна задокументированная поправка маршрутизации). Март–апрель видели другие '
         'исследования проекта: это проверка процедуры, а не слепой holdout.', '',
         '## Вердикты', '', '| Гипотеза | Вердикт |', '|---|---|',
         f"| R0 воспроизводимость train | {WORD[v['R0']]} |",
         f"| H1 экономика схем, преквенциально | {WORD[v['H1_prequential']]} |",
         f"| H1 экономика схем, заморожено на V | {WORD[v['H1_frozen']]} |",
         f"| H2 нулевой контроль | {WORD[v['H2']]} |",
         f"| H3 стоимость пассивного исполнения | {WORD[v['H3_cost']]} |",
         f"| H3 неблагоприятный отбор | {WORD[v['H3_selection']]} |",
         f"| H4 ранжирование «выставляться ли» (12/8/120) | {WORD[v['H4']]} |"]
    for h, x in v['H5'].items():
        L.append(f'| H5 стадия 0, горизонт {h} с | {WORD[x]} |')
    L += [f"| H6 знание схемы «шорт в нисходящем тренде хуже» | {WORD[v['H6']]} |", '',
          '## H1–H2: схемы на одном счёте 1 oz (PQ_30, язык очереди)', '',
          '| Вариант | сделок V | подтверждено в V | статусы библиотеки в конце |', '|---|---:|---:|---|']
    for k, x in sc.items():
        L.append(f"| {k} | {x['V']['trades']} | {x['promoted_V']} | {json.dumps(x['statuses'])} |")
    L += ['', 'Подтверждения в блоке V:', '']
    for k, x in sc.items():
        for e in x['events_V']:
            if e['kind'] == 'active':
                L.append(f"- {k}: {day(e['ns'])} {e['describe']}, t подтверждения {e['confirm_t']:+.2f}")
    L += ['', 'Все подтверждения в V, включая ложное в перемешанном контроле, описывают контексты, где результат **хуже** родителя. '
          'Ни одна схема не достигла LCB > 0, поэтому сделок нет во всех вариантах — включая taker-исполнение.', '',
          '**Почему H2 не пройдена.** Карантин — один односторонний тест t ≥ 2 через 15 дней, ложное подтверждение ≈3% на кандидата. '
          'С ростом числа кандидатов ложные подтверждения неизбежны; в V одно произошло. На торговлю оно не повлияло (схема «хуже» и '
          'сама убыточна), но критерий преднарегистрации нарушен. Для следующей версии процедуры нужна поправка на число кандидатов '
          '(например, t ≥ 3 или контроль доли ложных подтверждений) — менять текущую процедуру задним числом нельзя.', '',
          f"**R0.** Метрики train-блоков A и B всех сравниваемых вариантов совпадают с прежним прогоном; преквенциальная библиотека дала те же "
          f"{s['reproducibility']['prequential']['train_events']} событий на train. В перемешанном контроле внутренние события train отличаются "
          f"({s['reproducibility']['shuffled_context']['train_events']} против {s['reproducibility']['shuffled_context']['reference_events']}): "
          'перестановки идут по координатам, а для каждой координаты по всем дням, включая дни V. Генератор потребляется иначе, и '
          'начиная со второй координаты перестановки train-дней другие. Это другая реализация нуля, а не расхождение логики.', '',
          '## H3: пассивное исполнение против тейкера (парно, по дням)', '', '| План | тейкер $ | PQ_30 $ | улучшение [95% дни] |', '|---|---:|---:|---:|']
    for p, x in s['execution']['per_plan'].items():
        L.append(f"| {p} | {x['tt']:+.3f} | {x['pq']:+.3f} | {ci(x['improvement'])} |")
    e = s['execution']
    L += ['', f"Тейкер в тех же точках: там, где пассивная заявка не исполнилась, {e['taker_where_unfilled']:+.3f}$; где исполнилась "
          f"{e['taker_where_filled']:+.3f}$; дневной разрыв {ci(e['selection_gap'])}.", '',
          '## H4: ранжирование стоимости попытки (модель на окт–фев)', '',
          '| План | R² на V | верхний дециль $ | нижняя половина $ | разрыв [95% дни] | исполнено в верхнем |', '|---|---:|---:|---:|---:|---:|']
    for p, x in s['resting'].items():
        L.append(f"| {p} | {x['r2_vs_train_mean']:+.4f} | {x['top10']:+.3f} | {x['bottom50']:+.3f} | {ci(x['gap'])} | {x['top_fill']:.3f} |")
    L += ['', '## H5: opportunity (|ΔP| против причинной премии)', '', '| Горизонт, с | Месяц | навык vs масштабированной премии | наклон | издержки/движение |',
          '|---:|---|---:|---:|---:|']
    for h, r in s['opportunity'].items():
        for m, x in r.items():
            L.append(f"| {h} | {m} | {x['skill_vs_scaled']:+.4f} | {x['slope']:.3f} | {x['cost_over_move']:.3f} |")
    k = s['knowledge']
    L += ['', '## H6: знание из схем', '',
          f"Шорт 40/20/600 в нисходящем тренде: {k['child_mean']:+.3f}$ на попытку ({k['n_child']}), все шорты 40/20/600: "
          f"{k['parent_mean']:+.3f}$ ({k['n_parent']}); дневной остаток {ci(k['residual'])}.", '',
          '## Вывод', '',
          '- **Знание переносится.** Прогноз величины движения проходит переход стадии 0 на всех горизонтах в обоих месяцах. Эффект пассивного исполнения и '
          'неблагоприятного отбора воспроизводится. Ранжирование по очереди работает на коротком плане. Выученная схема «где хуже» подтверждается.',
          '- **Денег нет.** Агент на свежем периоде ни разу не торговал: ни одна программа не стала надёжно прибыльной после издержек. '
          'Это честный WAIT, но не решение цели роста капитала.',
          '- **Контроль ложных знаний требует ужесточения**: одно ложное подтверждение в нулевом контроле.', '',
          'Поправки к процедуре: ' + '; '.join(f"{a['file']}: {a['change']}" for a in pre.get('amendments', [])) + '.']
    return '\n'.join(L) + '\n'


def report():
    s = json.loads((REPORT / 'validation_summary.json').read_text(encoding='utf8'))
    pre = json.loads((REPORT / 'preregistration.json').read_text(encoding='utf8'))
    (REPORT / 'VALIDATION_RU.md').write_text(markdown(s, pre), encoding='utf8')
    return REPORT / 'VALIDATION_RU.md'


if __name__ == '__main__':
    print(report())
